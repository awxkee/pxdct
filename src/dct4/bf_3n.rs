impl<T: DctSample + Dct4MixedRadix9Sample> Dct4Butterfly81<T> {
    #[inline(always)]
    pub(crate) fn exec<S: BidirectionalStore<T>>(&self, data: &mut S) {
        let mut a_buffer = [T::zero(); 27];
        let mut c_buffer = [T::zero(); 27];
        let mut s_buffer = [T::zero(); 27];

        for n in 0..27 {
            a_buffer[n] = data[n * 3 + 1];
        }

        let mut sign = T::one();
        for n in 0..27 {
            let u0 = data[3 * n];
            let u1 = data[3 * n + 3 - 1];
            c_buffer[n] = u0 + u1;
            s_buffer[n] = (u0 - u1).mulsign(sign);

            sign = -sign;
        }

        _ = self.bf27.execute(&mut a_buffer);
        _ = self.bf27.execute(&mut c_buffer);
        _ = self.bf27.execute(&mut s_buffer);

        let q_modules = 81 / 3;
        let s = 2 * 81 / 3;

        for k in 0..q_modules {
            let c_v = c_buffer[k];
            let s_v = s_buffer[q_modules - 1 - k];
            let a_v = a_buffer[k];

            let twiddle = self.twiddles[k];

            let mut u0 = fmla(c_v, twiddle.re, s_v * twiddle.im);
            let mut u1 = u0;
            let mut v0 = fmla(c_v, twiddle.im, -s_v * twiddle.re);

            u0 += a_v;
            u1 *= T::HALF;
            v0 *= T::SQRT_3_OVER_2;
            u1 = u1 - a_v;

            let uc0 = u1 - v0;
            let uc1 = u1 + v0;

            data[k] = u0;
            data[s + k] = uc1;
            data[s - 1 - k] = uc0;
        }
    }
}

