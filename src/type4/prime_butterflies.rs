impl<T: DctSample + Dct4MixedRadix5Sample> Dct4Butterfly5<T> {
    #[inline(always)]
    pub(crate) fn exec<S: BidirectionalStore<T>>(&self, data: &mut S) {
        // This is autogenerated Radix-Q where Q = 5.
        let a_buffer = [data[2] * T::FRAC_1_SQRT_2];
        let c_buffer = [
            (data[0] + data[4]) * T::FRAC_1_SQRT_2,
            (data[1] + data[3]) * T::FRAC_1_SQRT_2,
        ];
        let s_buffer = [
            (data[0] - data[4]) * T::FRAC_1_SQRT_2,
            (data[1] - data[3]) * T::FRAC_1_SQRT_2,
        ];
        let c0 = c_buffer[0];
        let s0 = s_buffer[0];
        let s0_tw0 = s0 * T::D4_R5_ROT_TWIDDLE_1;
        let s0_tw1 = -s0 * T::D4_R5_ROT_TWIDDLE_0;
        let iq0 = fmla(c0, T::D4_R5_ROT_TWIDDLE_0, s0_tw0);
        let siq0 = fmla(c0, T::D4_R5_ROT_TWIDDLE_1, s0_tw1);
        let mut u0 = iq0;
        let mut u1 = u0;
        let mut v0 = siq0;
        u1 *= T::D4_R5_ROT_TWIDDLE_0;
        v0 *= T::D4_R5_ROT_TWIDDLE_1;
        let c1 = c_buffer[1];
        let s1 = s_buffer[1];
        let iq1 = fmla(c1, T::D4_R5_ROT_TWIDDLE_2, s1 * T::D4_R5_ROT_TWIDDLE_3);
        let siq1 = fmla(c1, T::D4_R5_ROT_TWIDDLE_3, -s1 * T::D4_R5_ROT_TWIDDLE_2);
        u0 += iq1;
        u1 = fmla(iq1, -T::D4_R5_ROT_TWIDDLE_3, u1);
        v0 = fmla(siq1, T::D4_R5_ROT_TWIDDLE_2, v0);
        let a0 = a_buffer[0];
        u0 += a0;
        u1 = u1 - a0;
        data[0] = u0;
        data[1] = u1 - v0;
        data[2] = u1 + v0;
        let mut u2 = iq0;
        let mut v2 = siq0;
        u2 *= T::D4_R5_ROT_TWIDDLE_3;
        v2 *= T::D4_R5_ROT_TWIDDLE_2;
        u2 = fmla(iq1, -T::D4_R5_ROT_TWIDDLE_0, u2);
        v2 = fmla(siq1, -T::D4_R5_ROT_TWIDDLE_1, v2);
        u2 += a0;
        data[3] = u2 - v2;
        data[4] = u2 + v2;
    }
}

impl<T: DctSample + Dct4MixedRadix5Sample> PxdctExecutor<T> for Dct4Butterfly5<T>
where
    f64: AsPrimitive<T>,
{
    fn execute(&self, data: &mut [T]) -> Result<(), PxdctError> {
        if !data.len().is_multiple_of(5) {
            return Err(PxdctError::InvalidSizeMultiplier(data.len(), self.length()));
        }
        for chunk in data.as_chunks_mut::<5>().0.iter_mut() {
            self.exec(&mut InPlaceStore::new(chunk));
        }
        Ok(())
    }

    fn execute_with_scratch(&self, data: &mut [T], _: &mut [T]) -> Result<(), PxdctError> {
        self.execute(data)
    }

    fn execute_into(&self, input: &[T], output: &mut [T]) -> Result<(), PxdctError> {
        self.execute_into_with_scratch(input, output, &mut [])
    }

    fn execute_into_with_scratch(
        &self,
        input: &[T],
        output: &mut [T],
        _: &mut [T],
    ) -> Result<(), PxdctError> {
        use crate::util::validate_oof_sizes;
        validate_oof_sizes!(input, output, 5);
        use crate::bidirectional::BiStore;
        for (src, dst) in input
            .as_chunks::<5>()
            .0
            .iter()
            .zip(output.as_chunks_mut::<5>().0.iter_mut())
        {
            self.exec(&mut BiStore::new(src, dst));
        }
        Ok(())
    }

    fn length(&self) -> usize {
        5
    }

    fn scratch_size(&self) -> usize {
        0
    }
}

