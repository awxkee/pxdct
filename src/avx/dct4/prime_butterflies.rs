        v0 = fma(siq2, T::D4_R7_ROT_TWIDDLE_0, v0);
        let a0 = a_buffer[0];
        u0 += a0;
        u1 = u1 - a0;
        data[0] = u0;
        data[1] = u1 - v0;
        data[2] = u1 + v0;
        let mut u2 = iq0;
        let mut v2 = siq0;
        u2 *= T::D4_R7_ROT_TWIDDLE_1;
        v2 *= T::D4_R7_ROT_TWIDDLE_0;
